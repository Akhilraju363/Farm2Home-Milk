-- India location master data: normalized State -> District -> City hierarchy used by the
-- registration Address step's cascading dropdowns (see LocationController). Read-only reference
-- data - no write endpoints are exposed; new/changed records go through a future migration.

CREATE TABLE customer.location_states (
    id            UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    name          VARCHAR(100) NOT NULL,
    code          VARCHAR(10)  NOT NULL,
    country_code  VARCHAR(2)   NOT NULL DEFAULT 'IN',
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_location_states_name UNIQUE (name),
    CONSTRAINT uq_location_states_code UNIQUE (code)
);

CREATE TABLE customer.location_districts (
    id         UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    state_id   UUID         NOT NULL REFERENCES customer.location_states(id),
    name       VARCHAR(100) NOT NULL,
    code       VARCHAR(20)  NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_location_districts_state_name UNIQUE (state_id, name),
    CONSTRAINT uq_location_districts_code UNIQUE (code)
);
CREATE INDEX idx_location_districts_state_id ON customer.location_districts(state_id);
CREATE INDEX idx_location_districts_active ON customer.location_districts(active);

CREATE TABLE customer.location_cities (
    id          UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    district_id UUID         NOT NULL REFERENCES customer.location_districts(id),
    name        VARCHAR(100) NOT NULL,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_location_cities_district_name UNIQUE (district_id, name)
);
CREATE INDEX idx_location_cities_district_id ON customer.location_cities(district_id);
CREATE INDEX idx_location_cities_active ON customer.location_cities(active);

